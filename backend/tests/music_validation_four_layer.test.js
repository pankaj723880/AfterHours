async function runTestSuite() {
  let truePositives = 0;   // Correctly approved music
  let falseNegatives = 0;  // Genuine music wrongly rejected
  let trueNegatives = 0;   // Non-music correctly rejected
  let falsePositives = 0;  // Non-music wrongly accepted (VIOLATION!)
  const latencies = [];

  console.log('--- SECTION 1: LAYER-BY-LAYER VALIDATION EVALUATION ---');

  for (let i = 0; i < BENCHMARK_CASES.length; i++) {
    const testCase = BENCHMARK_CASES[i];
    const { track, type, subType } = testCase;

    const res = await musicValidationService.validateTrack(track, { bypassCache: true });
    latencies.push(res.latencyMs);

    const isMusicExpected = type === 'music';

    if (isMusicExpected) {
      if (res.eligible) {
        truePositives++;
        console.log(`  ✅ [Layer 1-4 PASSED] ${subType}: "${track.title.slice(0, 50)}..." -> Approved (${res.category}, conf: ${res.confidence})`);
      } else {
        falseNegatives++;
        console.error(`  ❌ [FALSE REJECTION] ${subType}: "${track.title}" -> Rejected! Reason: ${res.reason}`);
      }
    } else {
      if (!res.eligible) {
        trueNegatives++;
        console.log(`  🛡️ [Layer 1-4 BLOCKED] ${subType}: "${track.title.slice(0, 50)}..." -> Blocked (${res.reason.slice(0, 45)}...)`);
      } else {
        falsePositives++;
        console.error(`  🚨 [CRITICAL VIOLATION: FALSE ACCEPTANCE] ${subType}: "${track.title}" was mistakenly accepted!`);
      }
    }

    // Verify all four layers returned structured results
    assert.ok(res.layerResults, `Track ${track.id} must include layerResults`);
    assert.ok(res.layerResults.layer1_category, 'Must include layer1_category result');
    assert.ok(res.layerResults.layer2_metadata, 'Must include layer2_metadata result');
    assert.ok(res.layerResults.layer3_ai, 'Must include layer3_ai result');
    assert.ok(res.layerResults.layer4_playback, 'Must include layer4_playback gate result');
  }

  // --- SECTION 2: PLAYBACK-LEVEL GATE BYPASS ATTEMPTS ---
  console.log('\n--- SECTION 2: PLAYBACK GATE BYPASS PREVENTION TEST ---');
  
  // Attempt 1: Direct playback attempt with empty or malformed track ID
  const invalidIdAttempt = await musicValidationService.validateTrack({ id: 'invalid_too_long_id_12345' });
  assert.strictEqual(invalidIdAttempt.eligible, false, 'Invalid YouTube ID must be rejected by Playback Gate');
  console.log('  ✅ Bypass Attempt 1 Blocked: Invalid YouTube ID strictly rejected');

  // Attempt 2: Direct playback attempt with null / undefined track
  const nullTrackAttempt = await musicValidationService.validateTrack(null);
  assert.strictEqual(nullTrackAttempt.eligible, false, 'Null track must be rejected by Playback Gate');
  console.log('  ✅ Bypass Attempt 2 Blocked: Null/undefined track strictly rejected');

  // Attempt 3: Direct playback attempt with non-music gaming video ID
  const gamingBypassAttempt = await musicValidationService.validateTrack({
    id: 'gM1P8_x7J9k',
    title: 'Minecraft Pro Gameplay Walkthrough Episode 5',
    channel: 'GamerChannel',
    categoryId: 20
  });
  assert.strictEqual(gamingBypassAttempt.eligible, false, 'Direct gaming playback must be blocked');
  console.log('  ✅ Bypass Attempt 3 Blocked: Direct gaming playback strictly blocked at Layer 4 Gate');

  // Attempt 4: Caching layer verification (subsequent request returns from cache with < 2ms latency)
  const cachedTest = await musicValidationService.validateTrack({
    id: 'BddP6PYo2gs',
    title: 'Kesariya - Brahmāstra',
    channel: 'Sony Music India'
  });
  assert.strictEqual(cachedTest.fromCache, true, 'Cached track must return fromCache: true');
  console.log(`  ✅ Cache Verification: Retrieved from memory cache in ${cachedTest.latencyMs}ms`);

  // --- METRIC CALCULATIONS ---
  const totalMusic = truePositives + falseNegatives;
  const totalNonMusic = trueNegatives + falsePositives;
  const precision = ((truePositives / (truePositives + falsePositives)) * 100).toFixed(2);
  const recall = ((truePositives / totalMusic) * 100).toFixed(2);
  const falseAcceptanceRate = ((falsePositives / totalNonMusic) * 100).toFixed(2);
  const falseRejectionRate = ((falseNegatives / totalMusic) * 100).toFixed(2);
  const avgLatency = (latencies.reduce((a, b) => a + b, 0) / latencies.length).toFixed(2);

  console.log('\n======================================================');
  console.log('      LOOPRA FOUR-LAYER MUSIC VALIDATION METRICS      ');
  console.log('======================================================');
  console.log(`Total Scenarios Evaluated:     ${BENCHMARK_CASES.length}`);
  console.log(`Music Classification Precision: ${precision}% (Target: 100%)`);
  console.log(`Music Classification Recall:    ${recall}% (Target: >= 98%)`);
  console.log(`False Acceptance Rate (FAR):    ${falseAcceptanceRate}% (Target: 0.00% STRICT)`);
  console.log(`False Rejection Rate (FRR):     ${falseRejectionRate}% (Target: 0.00%)`);
  console.log(`Average Validation Latency:     ${avgLatency} ms`);
  console.log('======================================================\n');

  // Strict acceptance criteria assertions
  assert.strictEqual(parseFloat(falseAcceptanceRate), 0.0, 'CRITICAL: False Acceptance Rate for non-music MUST BE 0.00%');
  assert.strictEqual(parseFloat(falseRejectionRate), 0.0, 'CRITICAL: False Rejection Rate for genuine music MUST BE 0.00%');
  assert.strictEqual(parseFloat(precision), 100.0, 'Music classification precision must be 100%');
  assert.strictEqual(parseFloat(recall), 100.0, 'Music classification recall must be 100%');

  console.log('🎉 ALL FOUR-LAYER VALIDATION SCENARIOS AND SECURITY GATES PASSED WITH 100% SUCCESS!');
}

runTestSuite().catch(err => {
  console.error('Test Suite Failed:', err);
  process.exit(1);
});
